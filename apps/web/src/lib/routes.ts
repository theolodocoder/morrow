/** Every in-app URL in one place (PRD §5). The authenticated app lives under /app; public reading under /works. */
export const routes = {
  library: '/app/library',
  onboarding: '/app/onboarding',
  profileSettings: '/app/settings/profile',
  accountSettings: '/app/settings/account',
  comics: '/comics',
  classics: '/classics',
  research: '/research',
  notifications: '/app/notifications',
  notificationSettings: '/app/settings/notifications',
  planSettings: '/app/settings/plan',
  invitations: '/app/invitations',
  reading: '/app/reading',
  badges: '/app/badges',
  dashboard: '/app/dashboard',
  suggestions: '/app/suggestions',
  reports: '/app/reports',
  moderationStatus: '/app/moderation-status',
  moderation: '/app/moderation',
  safetySettings: '/app/settings/safety',
  work: (workId: string) => `/app/works/${workId}`,
  chapter: (workId: string, chapterId: string) => `/app/works/${workId}/edit/${chapterId}`,
  proposals: (workId: string, status?: 'open' | 'closed') =>
    `/app/works/${workId}/proposals${status === 'closed' ? '?status=closed' : ''}`,
  proposal: (workId: string, proposalId: string) => `/app/works/${workId}/proposals/${proposalId}`,
  branch: (workId: string, branchId: string) => `/app/works/${workId}/branches/${branchId}`,
  branchCompare: (workId: string, branchId: string) => `/app/works/${workId}/branches/${branchId}/compare`,
  // public
  feed: '/',
  discover: '/discover',
  search: '/search',
  publicWork: (publicPath: string) => `/works/${publicPath}`,
  readChapter: (publicPath: string, chapterSlug: string) => `/works/${publicPath}/read/${chapterSlug}`,
  author: (username: string) => `/authors/${username}`,
} as const
