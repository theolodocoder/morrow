// Emits tokens.css: semantic tokens as CSS variables, light by default, dark by system preference or data-theme.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dark, fonts, light, motion, radius } from '../src/index.ts'

const vars = (t: Record<string, string>) =>
  Object.entries(t)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')
const css = `/* Generated by packages/tokens — do not edit by hand. */
:root {
${vars(light)}
${vars(Object.fromEntries(Object.entries(fonts).map(([k, v]) => [`font-${k}-family`, v])))}
${vars(Object.fromEntries(Object.entries(motion).map(([k, v]) => [`motion-${k}`, v])))}
${vars(Object.fromEntries(Object.entries(radius).map(([k, v]) => [`radius-${k}`, v])))}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${vars(dark)}
  color-scheme: dark;
}
@media (prefers-reduced-motion: reduce) {
  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }
}
`
mkdirSync(new URL('../dist', import.meta.url), { recursive: true })
writeFileSync(new URL('../dist/tokens.css', import.meta.url), css)
console.warn('tokens.css written')
